// Builds supabase/functions/sync-sheet/index.ts as ONE file (so it can be
// pasted into the Supabase dashboard editor) from the app's sheet parser.
// Run: node scripts/build-sync-function.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const parser = readFileSync(new URL('../app/src/lib/poSheetParser.ts', import.meta.url), 'utf8')
  .replace("import type { WorkBook, WorkSheet } from 'xlsx';\n", '')
  .replace("import * as XLSX from 'xlsx';", "import * as XLSX from 'npm:xlsx@0.18.5';\ntype WorkBook = XLSX.WorkBook;\ntype WorkSheet = XLSX.WorkSheet;");
const handler = readFileSync(new URL('../supabase/functions/sync-sheet/handler.ts.txt', import.meta.url), 'utf8');
writeFileSync(new URL('../supabase/functions/sync-sheet/index.ts', import.meta.url),
  '// GENERATED by scripts/build-sync-function.mjs. Edit handler.ts.txt or app/src/lib/poSheetParser.ts instead.\n' +
  handler.replace('/*__PARSER__*/', parser));
console.log('wrote supabase/functions/sync-sheet/index.ts');
